CREATE OR REPLACE TRIGGER WKSP_WSPOS.TRG_DISCOUNT_CONFIG_BIU
    BEFORE INSERT OR UPDATE
    ON WKSP_WSPOS.MST_DISCOUNT_CONFIG
    FOR EACH ROW
DECLARE
    V_PRODUCT_NAME    VARCHAR2 (200);
    V_CATEGORY_NAME   VARCHAR2 (200);
    V_CUSTOMER_NAME   VARCHAR2 (200);
BEGIN
    IF INSERTING
    THEN
        :NEW.DISCOUNT_CONFIG_NO := SEQ_DISCOUNT_CONFIG.NEXTVAL;

        :NEW.CONFIG_CODE := 'DIS-' || LPAD (:NEW.DISCOUNT_CONFIG_NO, 3, '0');
    END IF;

    IF :NEW.PRODUCT_NO IS NOT NULL
    THEN
        SELECT PRODUCT_NAME
          INTO V_PRODUCT_NAME
          FROM MST_PRODUCT
         WHERE PRODUCT_NO = :NEW.PRODUCT_NO;
    END IF;

    IF :NEW.CATEGORY_NO IS NOT NULL
    THEN
        SELECT CATEGORY_NAME
          INTO V_CATEGORY_NAME
          FROM MST_PRODUCT_CATEGORY
         WHERE CATEGORY_NO = :NEW.CATEGORY_NO;
    END IF;

    IF :NEW.CUSTOMER_NO IS NOT NULL
    THEN
        SELECT CUSTOMER_NAME
          INTO V_CUSTOMER_NAME
          FROM MST_CUSTOMER
         WHERE CUSTOMER_NO = :NEW.CUSTOMER_NO;
    END IF;

    :NEW.CONFIG_NAME :=
           'Discount - '
        || NVL (V_PRODUCT_NAME, '')
        || CASE
               WHEN V_CATEGORY_NAME IS NOT NULL THEN ' / ' || V_CATEGORY_NAME
               ELSE ''
           END
        || CASE
               WHEN V_CUSTOMER_NAME IS NOT NULL THEN ' / ' || V_CUSTOMER_NAME
               ELSE ''
           END
        || ' - '
        || TO_CHAR (:NEW.DISCOUNT_PERCENT)
        || '%';

    IF :NEW.EFFECTIVE_FROM IS NULL
    THEN
        :NEW.EFFECTIVE_FROM := SYSDATE;
    END IF;

    IF :NEW.ACTIVE_FLAG IS NULL
    THEN
        :NEW.ACTIVE_FLAG := 1;
    END IF;
END;
